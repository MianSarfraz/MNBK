alter table public.parties add column if not exists notes text;
alter table public.parties add column if not exists ref_no bigint generated by default as identity;
alter table public.transactions add column if not exists reference text;
alter table public.transactions add column if not exists ref_no bigint generated by default as identity;
alter table public.stock_adjustments add column if not exists is_opening boolean not null default false;
alter table public.kiln_entries add column if not exists firing_ref text;
-- Production can be recorded without a nakasi worker (worker is only needed for wages).
alter table public.kiln_entries alter column party_id drop not null;
alter table public.kiln_entries add constraint kiln_entries_worker_needed check (stage = 'nakasi' or party_id is not null);
alter table public.stock_adjustments add constraint stock_adjustments_opening_positive check (not is_opening or (stock = 'finished' and delta > 0));

-- No two active customers (or workers) with the same name.
do $u$ begin
  create unique index if not exists parties_unique_name on public.parties (kind, lower(btrim(name))) where deleted_at is null;
exception when unique_violation then
  raise notice 'Duplicate names already exist; fix them, then re-run to enforce unique names.';
end $u$;

-- ====== The seven brick types (one list for production, stock and sales) ======
do $bt$
declare
  types text[] := array['Awal', 'Awal Machine', 'Doum', 'Tirak', '9t', '9t Doum', '9t Tirak'];
  cats text[] := array['normal', 'normal', 'normal', 'normal', 'nine_t', 'nine_t', 'nine_t'];
  i int;
begin
  update public.qualities set name_en = '9t', name_ur = '9t' where kind = 'nakasi' and name_en = '9T' and deleted_at is null;
  for i in 1 .. array_length(types, 1) loop
    if not exists (select 1 from public.qualities where kind = 'nakasi' and lower(name_en) = lower(types[i]) and deleted_at is null) then
      insert into public.qualities (name_en, name_ur, kind, category, sort_order, created_by)
      values (types[i], types[i], 'nakasi', cats[i]::public.quality_category, i, '00000000-0000-0000-0000-000000000000');
    end if;
    update public.qualities set sort_order = i, category = cats[i]::public.quality_category, is_active = true
    where kind = 'nakasi' and lower(name_en) = lower(types[i]) and deleted_at is null;
  end loop;
  -- Older names stay for history but leave the drop-downs.
  update public.qualities set is_active = false
  where deleted_at is null and (kind = 'sale' or (kind = 'nakasi' and lower(name_en) <> all (select lower(x) from unnest(types) x)));
end $bt$;

-- ====== Initial customers + Nakad Bikri (cash) ======
insert into public.parties (kind, name, is_cash, created_by)
select 'customer', v.n, v.n = 'Nakad Bikri', '00000000-0000-0000-0000-000000000000'
from (values ('Imran urf polu'), ('Arshad Jamadar'), ('Rana Shani'), ('Dilshad saleman'), ('Shaukat Rehmani'), ('Nakad Bikri')) v(n)
where not exists (select 1 from public.parties p where p.kind = 'customer' and lower(btrim(p.name)) = lower(v.n) and p.deleted_at is null);
update public.parties set is_cash = true, is_active = true where kind = 'customer' and lower(btrim(name)) = 'nakad bikri' and deleted_at is null;

-- Nakad Bikri can't be removed, switched off or turned into a credit customer.
create or replace function public.protect_cash_customer()
returns trigger language plpgsql set search_path = public as $$
begin
  if old.is_cash and (new.deleted_at is not null or not new.is_active or not new.is_cash) then
    raise exception 'Nakad Bikri is permanent and cannot be removed';
  end if;
  return new;
end;
$$;
create trigger protect_cash_customer before update on public.parties for each row execute function public.protect_cash_customer();

-- ====== Nakad Bikri sales are paid in cash automatically (kept in step when a sale is edited) ======
create or replace function public.sync_cash_sale(_sale uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  s record;
  total bigint;
  rid uuid;
begin
  select sa.*, p.is_cash into s from public.sales sa join public.parties p on p.id = sa.customer_id where sa.id = _sale;
  if s is null or not s.is_cash then return; end if;
  select coalesce(sum((quantity * rate_per_1000 + 500) / 1000), 0) - s.discount + s.delivery_charges into total
    from public.sale_items where sale_id = _sale and deleted_at is null;
  select id into rid from public.transactions where sale_id = _sale and category = 'cash_sale' and deleted_at is null limit 1;
  if s.deleted_at is not null or total <= 0 then
    if rid is not null then update public.transactions set deleted_at = now() where id = rid; end if;
  elsif rid is null then
    insert into public.transactions (entry_date, party_id, sale_id, kind, direction, amount, method, handler_user_id, category, note, created_by)
    values (s.entry_date, s.customer_id, _sale, 'sale_receipt', 'in', total, 'cash', coalesce(auth.uid(), s.created_by), 'cash_sale', 'Nakad Bikri — paid at sale', coalesce(auth.uid(), s.created_by));
  else
    update public.transactions set amount = total, entry_date = s.entry_date where id = rid and (amount <> total or entry_date <> s.entry_date);
  end if;
end;
$$;

create or replace function public.trg_sync_cash_sale()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_table_name = 'sales' then
    perform public.sync_cash_sale(new.id);
  else
    perform public.sync_cash_sale(new.sale_id);
  end if;
  return null;
end;
$$;
create trigger sync_cash_sale after insert or update on public.sales for each row execute function public.trg_sync_cash_sale();
create trigger sync_cash_sale after insert or update on public.sale_items for each row execute function public.trg_sync_cash_sale();

-- Money "received now" is ignored for Nakad Bikri (it is always fully paid).
create or replace function public.create_sale(
  _entry_date date, _customer_id uuid, _vehicle_no text, _driver_name text, _discount bigint, _delivery bigint,
  _note text, _items jsonb, _paid bigint, _method public.pay_method, _handler uuid
) returns uuid
language plpgsql security invoker set search_path = public as $$
declare
  sid uuid;
  it jsonb;
  gross bigint := 0;
  cash boolean;
begin
  if _items is null or jsonb_array_length(_items) = 0 then raise exception 'Invoice needs at least one line'; end if;
  select is_cash into cash from public.parties where id = _customer_id;
  insert into public.sales (entry_date, customer_id, vehicle_no, driver_name, discount, delivery_charges, note, created_by)
  values (_entry_date, _customer_id, nullif(btrim(_vehicle_no), ''), nullif(btrim(_driver_name), ''),
          coalesce(_discount, 0), coalesce(_delivery, 0), nullif(btrim(_note), ''), auth.uid())
  returning id into sid;
  for it in select * from jsonb_array_elements(_items) loop
    insert into public.sale_items (sale_id, quality_id, quantity, rate_per_1000, created_by)
    values (sid, (it ->> 'quality_id')::uuid, (it ->> 'quantity')::bigint, (it ->> 'rate_per_1000')::bigint, auth.uid());
    gross := gross + ((it ->> 'quantity')::bigint * (it ->> 'rate_per_1000')::bigint + 500) / 1000;
  end loop;
  if gross - coalesce(_discount, 0) + coalesce(_delivery, 0) < 0 then raise exception 'Discount is larger than the invoice'; end if;
  if not coalesce(cash, false) and coalesce(_paid, 0) > 0 then
    if _handler is null then raise exception 'Choose who received the money'; end if;
    insert into public.transactions (entry_date, party_id, sale_id, kind, direction, amount, method, handler_user_id, category, created_by)
    values (_entry_date, _customer_id, sid, 'sale_receipt', 'in', _paid, coalesce(_method, 'cash'), _handler, 'sale', auth.uid());
  end if;
  return sid;
end;
$$;

-- ====== Views ======
-- Stock per brick type: opening + production − sold ± adjustments. Sales of an older "sale" quality count against
-- the brick type it was linked to.
drop view if exists public.finished_stock;
create view public.finished_stock
with (security_invoker = true) as
select q.id as quality_id, q.name_en, q.name_ur, q.category, q.sort_order, q.is_active,
       coalesce(op.n, 0)::bigint as opening,
       coalesce(pr.n, 0)::bigint as produced,
       coalesce(so.n, 0)::bigint as sold,
       coalesce(ad.n, 0)::bigint as adjusted,
       (coalesce(op.n, 0) + coalesce(pr.n, 0) - coalesce(so.n, 0) + coalesce(ad.n, 0))::bigint as balance
from public.qualities q
left join (select quality_id, sum(delta) n from public.stock_adjustments where stock = 'finished' and is_opening and deleted_at is null group by quality_id) op on op.quality_id = q.id
left join (select quality_id, sum(delta) n from public.stock_adjustments where stock = 'finished' and not is_opening and deleted_at is null group by quality_id) ad on ad.quality_id = q.id
left join (select quality_id, sum(count) n from public.kiln_entries where stage = 'nakasi' and deleted_at is null group by quality_id) pr on pr.quality_id = q.id
left join (
  select case when sq.kind = 'nakasi' then sq.id else sq.stock_quality_id end as qid, sum(si.quantity) n
  from public.sale_items si
  join public.sales s on s.id = si.sale_id and s.deleted_at is null
  join public.qualities sq on sq.id = si.quality_id
  where si.deleted_at is null
  group by 1
) so on so.qid = q.id
where q.deleted_at is null and q.kind = 'nakasi';

-- One row per brick line sold (the Sales Register).
create view public.sale_lines
with (security_invoker = true) as
select si.id as item_id, s.id as sale_id, s.invoice_no, s.entry_date, s.customer_id, s.vehicle_no, s.driver_name, s.note,
       si.quality_id, si.quantity, si.rate_per_1000, ((si.quantity * si.rate_per_1000 + 500) / 1000)::bigint as amount, s.season_id
from public.sale_items si
join public.sales s on s.id = si.sale_id and s.deleted_at is null
where si.deleted_at is null;

-- Customer accounts: outstanding = opening + purchases − payments (positive = customer owes us).
create view public.customer_accounts
with (security_invoker = true) as
select p.id as party_id, p.ref_no, p.name, p.phone, p.address, p.notes, p.is_cash, p.is_active,
       (-p.opening_balance)::bigint as opening_due,
       coalesce(st.bricks, 0)::bigint as bricks,
       coalesce(st.total, 0)::bigint as purchases,
       coalesce(st.n, 0)::bigint as sales_count,
       (coalesce(l.payments_in, 0) - coalesce(l.payments_out, 0))::bigint as payments,
       (coalesce(l.deductions, 0) - coalesce(l.credits, 0))::bigint as adjustments,
       (-coalesce(l.balance, -p.opening_balance))::bigint as outstanding,
       st.last_sale
from public.parties p
left join public.party_ledger l on l.party_id = p.id
left join (select customer_id, sum(bricks) bricks, sum(total) total, count(*) n, max(entry_date) last_sale from public.sale_totals group by customer_id) st on st.customer_id = p.id
where p.deleted_at is null and p.kind = 'customer';

GRANT SELECT ON public.finished_stock, public.sale_lines, public.customer_accounts TO authenticated;
GRANT SELECT ON public.finished_stock, public.sale_lines, public.customer_accounts TO service_role;
