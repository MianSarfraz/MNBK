-- Fuel khatta: coal trucks, wood, boora (and anything else) bought from agents on credit, and what we've paid them.
-- Agents are parties of kind 'vendor'. A purchase is what we owe; a payment is an ordinary money-book row
-- (transactions, kind 'expense', direction 'out', party = the agent), so it also shows in the Expense khatta.
-- Owed to an agent = opening balance + purchases − payments (positive = we owe them).

create table public.purchases (
  id uuid primary key default gen_random_uuid(),
  ref_no bigint generated by default as identity,
  entry_date date not null,
  season_id uuid references public.seasons(id),
  supplier_id uuid not null references public.parties(id),
  material text not null default 'coal' check (material in ('coal', 'wood', 'boora', 'other')),
  truck_no text,
  quantity numeric(14, 3) check (quantity is null or quantity > 0),
  unit text check (unit is null or unit in ('ton', 'mann', 'kg', 'truck', 'trolley', 'bag')),
  rate bigint check (rate is null or rate >= 0),
  amount bigint not null check (amount >= 0),
  reference text,
  notes text,
  created_by uuid not null default auth.uid(),
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index purchases_supplier_idx on public.purchases (supplier_id, entry_date) where deleted_at is null;
create index purchases_date_idx on public.purchases (entry_date) where deleted_at is null;

create or replace function public.validate_purchase()
returns trigger language plpgsql set search_path = public as $$
begin
  if (select kind from public.parties where id = new.supplier_id) <> 'vendor' then
    raise exception 'Purchases are from an agent (vendor)';
  end if;
  return new;
end;
$$;
create trigger validate_purchase before insert or update on public.purchases for each row execute function public.validate_purchase();
create trigger touch_purchases before update on public.purchases for each row execute function public.touch_row();
create trigger guard_purchases_season before insert or update on public.purchases for each row execute function public.guard_season();
create trigger audit_purchases after insert or update or delete on public.purchases for each row execute function public.audit_row();

GRANT SELECT, INSERT, UPDATE ON public.purchases TO authenticated;
GRANT ALL ON public.purchases TO service_role;
ALTER TABLE public.purchases ENABLE ROW LEVEL SECURITY;
CREATE POLICY "owners read purchases" ON public.purchases FOR SELECT TO authenticated USING (public.has_role(auth.uid(), 'owner'));
CREATE POLICY "owners write purchases" ON public.purchases FOR INSERT TO authenticated WITH CHECK (public.has_role(auth.uid(), 'owner'));
CREATE POLICY "owners update purchases" ON public.purchases FOR UPDATE TO authenticated USING (public.has_role(auth.uid(), 'owner'));

-- One row per agent. Mirrors supplierAccount() in src/lib/kiln-math.ts.
create or replace view public.supplier_accounts
with (security_invoker = true) as
select p.id as party_id, p.ref_no, p.name, p.phone, p.notes, p.is_active,
       p.opening_balance::bigint as opening,
       coalesce(pu.total, 0)::bigint as purchases,
       coalesce(pu.coal, 0)::bigint as coal,
       coalesce(pu.wood, 0)::bigint as wood,
       coalesce(pu.boora, 0)::bigint as boora,
       coalesce(pu.other, 0)::bigint as other,
       coalesce(pu.n, 0)::bigint as purchase_count,
       coalesce(pu.trucks, 0)::bigint as coal_trucks,
       coalesce(pa.paid, 0)::bigint as payments,
       (p.opening_balance + coalesce(pu.total, 0) - coalesce(pa.paid, 0))::bigint as balance,
       pu.last_purchase, pa.last_payment
from public.parties p
left join (
  select supplier_id, sum(amount) total, count(*) n, max(entry_date) last_purchase,
         sum(amount) filter (where material = 'coal') coal, sum(amount) filter (where material = 'wood') wood,
         sum(amount) filter (where material = 'boora') boora, sum(amount) filter (where material = 'other') other,
         count(*) filter (where material = 'coal') trucks
  from public.purchases where deleted_at is null group by supplier_id
) pu on pu.supplier_id = p.id
left join (
  select party_id, sum(case when direction = 'out' then amount else -amount end) paid, max(entry_date) last_payment
  from public.transactions where deleted_at is null and kind <> 'adjustment' group by party_id
) pa on pa.party_id = p.id
where p.deleted_at is null and p.kind = 'vendor';

GRANT SELECT ON public.supplier_accounts TO authenticated, service_role;
