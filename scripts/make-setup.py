# Builds supabase/setup.sql from drizzle/migrations/*.sql as ONE idempotent script
# (safe on a new project, an older setup, or re-runs). Usage: python3 scripts/make-setup.py
import glob, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else "."
VIEWS = ["party_ledger", "party_earnings", "sale_totals", "finished_stock", "raw_stock", "raw_store_stock", "sale_lines", "customer_accounts"]

parts = []
for f in sorted(glob.glob(f"{root}/drizzle/migrations/0*.sql")):
    s = open(f).read()
    # enums: skip if they already exist
    s = re.sub(r"^create type (public\.\w+) as enum \(([^;]*)\);", r"do $t$ begin create type \1 as enum (\2); exception when duplicate_object then null; end $t$;", s, flags=re.M | re.I)
    s = re.sub(r"^create table (public\.)", r"create table if not exists \1", s, flags=re.M)
    s = re.sub(r"^create (unique )?index (?!if not exists)(\w+)", r"create \1index if not exists \2", s, flags=re.M)
    s = re.sub(r"^create view ", "create or replace view ", s, flags=re.M)
    # policies / triggers: drop then recreate
    s = re.sub(r'^(CREATE POLICY ("[^"]+") ON ([\w.]+))', r"DROP POLICY IF EXISTS \2 ON \3;\n\1", s, flags=re.M)
    s = re.sub(r"^(create trigger (\w+)\s+(?:before|after)[^;]*? on ([\w.]+))", r"drop trigger if exists \2 on \3;\n\1", s, flags=re.M | re.S)
    # named constraints added later
    s = re.sub(r"^(alter table [\w.]+ add constraint \w+ [^;]*;)", r"do $c$ begin \1 exception when duplicate_object then null; end $c$;", s, flags=re.M)
    # seed rows only into empty tables
    s = re.sub(r"^(insert into public\.(qualities|expense_categories) \([^)]*\) values\n.*?;)",
               lambda m: f"do $seed$ begin if not exists (select 1 from public.{m.group(2)}) then\n{m.group(1)}\nend if; end $seed$;", s, flags=re.M | re.S)
    parts.append(f"\n-- ===== {f.split('/')[-1]} =====\n{s.strip()}\n")

head = """-- Mian Nawaz Bricks — complete database setup (all migrations in drizzle/migrations).
-- Safe to run on ANY state: a brand-new empty Supabase project, a project that already ran an older
-- setup.sql, or one that already ran this file. Every step skips itself if already done; no data is touched.
-- Supabase → SQL Editor → paste everything → Run.   (Generated by scripts/make-setup.py — do not edit by hand.)

-- Views hold no data; drop and rebuild them so their columns are always current.
""" + "".join(f"drop view if exists public.{v} cascade;\n" for v in VIEWS)
open(f"{root}/supabase/setup.sql", "w").write(head + "".join(parts))
print("wrote supabase/setup.sql")
