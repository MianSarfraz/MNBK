export type Key = keyof typeof dict;
const DAYS = ["Thu", "Fri", "Sat", "Sun", "Mon", "Tue", "Wed"];

type Ctx = { t: (k: Key) => string; days: string[] };
const I18n = createContext<Ctx | null>(null);
const t = (k: Key) => dict[k];
const value: Ctx = { t, days: DAYS };

/** Labels live in one dictionary so wording stays consistent across screens. */
export function I18nProvider({ children }: { children: ReactNode }) {
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useT() {
  const c = useContext(I18n);
  if (!c) throw new Error("I18nProvider missing");
  return c;
}

/** Whole rupees / bricks with thousands separators. */
export function fmt(n: number | null | undefined) {
  if (n == null) return "—";
  return n.toLocaleString("en-PK");
}

/** ISO date → dd-mm-yyyy, as written in the paper register. */
export function fmtDate(d: string | null | undefined) {
  if (!d) return "—";
  const [y, m, day] = d.slice(0, 10).split("-");
  return `${day}-${m}-${y}`;
}

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
/** ISO date → "Nov 2026". */
export function fmtMonth(d: string) {
  return `${MONTHS[Number(d.slice(5, 7)) - 1]} ${d.slice(0, 4)}`;
}
